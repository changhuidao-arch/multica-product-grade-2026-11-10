from playwright.sync_api import sync_playwright,expect
from pathlib import Path
import json
out=Path('qa/task-context');out.mkdir(exist_ok=True)
checks=[];errors=[]
def ok(name,v=True):
 assert v,name
 checks.append(name)
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='C:/Program Files/Google/Chrome/Application/chrome.exe',headless=True)
 page=b.new_page(viewport={'width':1568,'height':1003});page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:55321/new.html#tasks',wait_until='networkidle')
 page.locator('.task-name a').filter(has_text='加密功能迁移').click()
 expect(page.locator('.task-subject-copy h2')).to_have_text('加密功能迁移')
 ok('task entry subject retained')
 ok('business status separate','处理中' in page.locator('.task-context-meta').inner_text())
 ok('static task view omits source-system link',page.locator('.task-external').count()==0)
 page.locator('.task-hierarchy summary').click();ok('seven child links',page.locator('.task-hierarchy a').count()==7)
 page.locator('.task-hierarchy summary').click()
 row=page.locator('.time-row').first;run=row.get_attribute('data-run');row.click()
 page.locator('.view-tabs a').filter(has_text='调用流程图').click()
 expect(page.locator('.node.selected')).to_have_attribute('data-run',run);ok('timeline to graph same run')
 page.locator('.view-tabs a').filter(has_text='运行时间线').click()
 expect(page.locator('.time-row.selected')).to_have_attribute('data-run',run);ok('graph to timeline same run')
 page.screenshot(path=str(out/'detail.png'))
 page.locator('.inspector .run-links a').filter(has_text='时间瀑布').click()
 expect(page.locator('#task-select')).to_be_enabled()
 expect(page.locator('.task-subject-copy h2')).to_have_text('加密功能迁移');ok('waterfall retains full task title')
 ok('return to origin timeline','返回任务时间线' in page.locator('.return-graph').inner_text())
 ok('run belongs to original task',page.locator('#context-run').input_value()==run)
 page.screenshot(path=str(out/'waterfall.png'))
 page.locator('.run-context-controls nav a').filter(has_text='执行过程').click()
 expect(page.locator('#task-select')).to_be_enabled();expect(page.locator('.task-subject-copy h2')).to_have_text('加密功能迁移')
 ok('process retains task and run',page.locator('#context-run').input_value()==run)
 page.screenshot(path=str(out/'process.png'))
 page.locator('.return-graph').click()
 expect(page.locator('.time-row.selected')).to_have_attribute('data-run',run);ok('return retains original selected run')
 d=json.load(open('public/new-data.json',encoding='utf-8'));other=next(x for x in d['issues'] if x['issue']['identifier']=='CXTE-4')
 page.locator('#task-select').select_option(other['issue']['id'])
 expect(page.locator('.time-row')).to_have_count(9);ok('task switch loads own runs')
 page.locator('.view-tabs a').filter(has_text='调用流程图').click()
 page.locator('.inspector .run-links a').filter(has_text='执行过程').click()
 expect(page.locator('#task-select')).to_be_enabled()
 ok('return to graph from graph','返回调用图' in page.locator('.return-graph').inner_text())
 empty=next(x for x in d['issues'] if not x['runs'])
 page.locator('#task-select').select_option(empty['issue']['id'])
 expect(page.locator('.task-subject-copy h2')).to_have_text(empty['issue']['title'])
 ok('no-run task falls back to its own detail',page.locator('.time-row').count()==0)
 for width,height in [(1366,768),(390,844)]:
  page.set_viewport_size({'width':width,'height':height})
  for name,url in [('detail','new.html#detail?issue=CXTE-3'),('graph','new.html#graph?issue=CXTE-3'),('waterfall','waterfall.html?run='+run),('process','process.html?run='+run)]:
   page.goto('http://127.0.0.1:55321/'+url,wait_until='networkidle')
   expect(page.locator('#task-select')).to_be_enabled()
   ok(f'{width} {name} no overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
   if name in ['waterfall','process'] and width>700:ok(name+' usable reading height',page.locator('#timeline-scroll' if name=='waterfall' else '#flow-scroll').bounding_box()['height']>180)
   page.screenshot(path=str(out/f'{name}-{width}.png'))
 ok('no script errors',not errors)
 b.close()
(out/'checks.json').write_text(json.dumps({'checks':checks,'errors':errors},ensure_ascii=False,indent=2),encoding='utf-8')
print(len(checks),'checks passed')
