from pathlib import Path
import json
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parent
QA=ROOT/'qa'/'inline-waterfall'
QA.mkdir(exist_ok=True)
URL='http://127.0.0.1:55321/waterfall.html'
checks=[]
errors=[]
def check(name,passed=True):
    assert passed,name
    checks.append(name)
def overflow(page,label):
    check(label,page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1'))
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='C:/Program Files/Google/Chrome/Application/chrome.exe',headless=True)
    context=browser.new_context(viewport={'width':1440,'height':1000},device_scale_factor=1)
    page=context.new_page()
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(URL,wait_until='networkidle')
    page.locator('#workspace').wait_for(state='visible')
    check('Snapshot count displayed accurately','1,088' in page.locator('#record-count').inner_text() and '343' in page.locator('#record-count').inner_text())
    check('Twenty long segments available initially',page.locator('.record').count()==20)
    page.screenshot(path=str(QA/'desktop-collapsed.png'))
    bar=page.locator('#row-record-244 .time-bar').bounding_box()
    page.locator('#row-record-244').click()
    check('Click opens detail under corresponding row',page.locator('[data-record="record-244"] .inline-detail').count()==1)
    after=page.locator('#row-record-244 .time-bar').bounding_box()
    check('Expansion preserves horizontal time geometry',abs(bar['x']-after['x'])<1 and abs(bar['width']-after['width'])<1)
    check('Parsed summary preserves both warnings',page.locator('.warning-item').count()==2)
    check('Summary distinguishes 411 source lines from returned subset','411 行' in page.locator('.detail-body').inner_text() and '筛选' in page.locator('.detail-body').inner_text())
    page.screenshot(path=str(QA/'desktop-shell-inline.png'))
    page.locator('#row-record-244').click()
    check('Second click collapses same row',page.locator('.inline-detail').count()==0)
    for seq in ['244','747','796','61']:
        page.locator(f'[data-example="{seq}"]').click()
        check('Example '+seq+' has exactly one open row',page.locator('.inline-detail').count()==1 and page.locator(f'#row-record-{seq}').get_attribute('aria-expanded')=='true')
        overflow(page,'Desktop '+seq+' no document overflow')
        page.screenshot(path=str(QA/f'desktop-example-{seq}.png'))
    check('Read file becomes formatted document',page.locator('.detail-body .document h2').count()>0 and page.locator('.detail-body .document table').count()>0)
    check('Read truncation remains visible','已截断' in page.locator('.capture-note').inner_text())
    page.locator('[data-example="747"]').click()
    check('Truncated write input decoded into document',page.locator('.detail-body').inner_text().find('验收与自测条目')>=0 and page.locator('.document table').count()>0)
    check('Truncated write never claims complete data','无法恢复缺失部分' in page.locator('.capture-note').inner_text())
    page.locator('.detail-top [data-read]').click()
    check('Full reader opens',page.locator('#reader').evaluate('(el)=>el.open'))
    page.locator('#reader-search').fill('验收')
    check('Full reader searches parsed content',page.locator('#reader-content mark').count()>5)
    page.locator('#next-match').click()
    check('Search advances through matches',page.locator('#match-count').inner_text().startswith('2 /'))
    page.screenshot(path=str(QA/'desktop-long-input-reader.png'))
    page.locator('#reader-search').fill('')
    for i in range(4):
        page.locator('[data-reader-tab="input"]').click()
        page.keyboard.press('ArrowRight')
        check('Reader keyboard tabs remain single-step '+str(i),page.locator('[data-reader-tab="output"]').get_attribute('aria-selected')=='true')
    page.locator('[data-reader-tab="raw"]').click()
    check('Raw view preserves original truncation flags','inputTruncated' in page.locator('#reader-content').inner_text())
    with page.expect_download() as download:
        page.locator('#download-record').click()
    download.value.save_as(str(QA/'captured-record.json'))
    saved=json.loads((QA/'captured-record.json').read_text(encoding='utf-8'))
    check('Downloaded record preserves exact original preview',saved['record']['call']['inputTruncated'] is True and 'preview' in saved['record']['call']['input'] and saved['source']['demo'] is False)
    page.keyboard.press('Escape')
    check('Escape closes reader and restores row action focus',not page.locator('#reader').evaluate('(el)=>el.open') and page.evaluate('document.activeElement.hasAttribute("data-read")'))
    page.locator('[data-example="796"]').click()
    check('Edit payload uses real replacement diff',page.locator('.diff-line.add').count()>0 and page.locator('.diff-line.remove').count()>0)
    page.locator('[data-tab="input"]').focus()
    page.keyboard.press('ArrowRight')
    check('Inline keyboard tabs work',page.locator('[data-tab="output"]').get_attribute('aria-selected')=='true')
    page.locator('#collapse-all').click()
    check('Global collapse restores timeline',page.locator('.inline-detail').count()==0)
    page.locator('#search').fill('no-record-matches-this-text')
    check('Empty search has recovery',page.locator('#clear-search').is_visible())
    page.locator('#clear-search').click()
    check('Recovery restores records',page.locator('.record').count()>0)
    page.locator('#kind').select_option('tool')
    check('Type filter excludes gaps',page.locator('.record .kind-dot:not(.tool)').count()==0)
    page.locator('#search').fill('#244')
    check('Search checks entire captured run',page.locator('#row-record-244').count()==1)
    page.locator('#zoom-in').click()
    check('Zoom reveals time-window pan',page.locator('#pan-control').is_visible())
    page.locator('#pan').focus()
    page.keyboard.press('End')
    check('Pan range changes viewport',int(page.locator('#pan').input_value())>0)
    page.locator('#zoom-fit').click()
    check('Fit restores complete time span',page.locator('#pan-control').is_hidden())
    page.reload(wait_until='networkidle')
    check('Search and filters survive reload',page.locator('#search').input_value()=='#244' and page.locator('#kind').input_value()=='tool')

    mobile=context.new_page()
    mobile.set_viewport_size({'width':390,'height':844})
    mobile.on('pageerror',lambda e:errors.append(str(e)))
    mobile.goto(URL,wait_until='networkidle')
    for seq in ['244','747','796','61']:
        mobile.locator(f'[data-example="{seq}"]').click()
        overflow(mobile,'Mobile '+seq+' no document overflow')
        mobile.locator(f'#row-record-{seq}').scroll_into_view_if_needed()
        mobile.screenshot(path=str(QA/f'mobile-example-{seq}.png'))
        mobile.locator('.detail-top [data-read]').click()
        overflow(mobile,'Mobile reader '+seq+' no document overflow')
        mobile.locator('#close-reader').click()
        mobile.locator('.detail-top [data-close]').click()
        check('Mobile collapse '+seq,page.locator('#reader').evaluate('(el)=>!el.open') and mobile.locator('.inline-detail').count()==0)
    mobile.locator('[data-example="747"]').click()
    mobile.locator('.detail-top [data-read]').click()
    mobile.screenshot(path=str(QA/'mobile-reader.png'))

    laptop=context.new_page()
    laptop.set_viewport_size({'width':1366,'height':768})
    laptop.goto(URL,wait_until='networkidle')
    laptop.locator('[data-example="244"]').click()
    overflow(laptop,'Laptop no document overflow')
    laptop.screenshot(path=str(QA/'laptop-shell.png'))
    check('Laptop timeline retains usable scroll area',laptop.locator('#timeline-scroll').bounding_box()['height']>300)

    recovery=context.new_page()
    recovery.route('**/waterfall-data.json',lambda route:route.abort(),times=1)
    recovery.goto(URL)
    recovery.locator('#load-error').wait_for(state='visible')
    recovery.locator('#retry-load').click()
    recovery.locator('#workspace').wait_for(state='visible')
    check('Data-load failure retries without page reload')
    comparison=context.new_page()
    comparison.goto('http://127.0.0.1:55321/#waterfall',wait_until='networkidle')
    check('Comparison website exposes the new interaction entry',comparison.locator('#interactive-entry').is_visible())
    comparison.locator('#interactive-entry a').click()
    check('Entry navigates to working real-data prototype','waterfall.html' in comparison.url)
    check('No application JavaScript errors',not errors)
    (QA/'verification.json').write_text(json.dumps({'passed':len(checks),'checks':checks,'errors':errors},ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({'passed':len(checks),'errors':errors,'qa':str(QA)},ensure_ascii=False))
    browser.close()
